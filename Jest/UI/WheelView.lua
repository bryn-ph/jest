-- WheelView: draws a wheel (ring segments, slice icons, eased gold highlight, centre icon/label).
-- Purely visual and insecure. Used by the in-game wheel (UI/Skin.lua) and by the preview in the
-- options panel, so the two always look the same.
--
--   local view = ns.WheelView.Create(parent, { name = ..., interactive = bool,
--                                              labelFont = ..., onSlotCreated = fn(slot, i) })
--   view:Layout(slices, { radius =, deadZone =, iconSize =, centreIconSize = })
--   view:SetHighlight(i)  -- gold segment eases to slice i (nil fades it out)
--   view:SetEmphasis(i)   -- slice i's icon grows (nil = none)
--   view:SetCentre(texture, text, dim)
--   view:Update(elapsed)  -- call every frame while shown, drives the easing
local addonName, ns = ...

local View = {}
ns.WheelView = View

local MASK = "Interface\\CharacterFrame\\TempPortraitAlphaMask"
local MEDIA = "Interface\\AddOns\\" .. addonName .. "\\Media\\"

-- Wedge art (Media/wedge_<N>.tga, generated by tools/gen_wedges.py). Wheels with a slice count
-- outside WEDGE_MIN..WEDGE_MAX fall back to the plain circular backdrop + per-icon glow.
local WEDGE_MIN, WEDGE_MAX = 2, 12
local WEDGE_OUTER = 0.98       -- segment's outer edge as a fraction of the texture half-size (gen_wedges.py OUTER)
local GLOW_SCALE = 0.84        -- glow segment is drawn this much smaller in its texture (gen_wedges.py GLOW_SCALE)
local HIGHLIGHT_TURN = 22      -- higher = faster highlight sweep between slices
local HIGHLIGHT_FADE = 16      -- higher = faster highlight fade in/out
local SCALE_SPEED = 18         -- higher = snappier icon grow/shrink
local EMPHASIS_SCALE = 1.2
local WEDGE_COLOR = { 0.05, 0.05, 0.07, 0.62 }
local WEDGE_EMPTY_ALPHA = 0.32
local GOLD = { 1, 0.82, 0.2 }

local function addCircleMask(parent, texture)
	local mask = parent:CreateMaskTexture()
	mask:SetTexture(MASK, "CLAMPTOBLACKADDITIVE", "CLAMPTOBLACKADDITIVE")
	mask:SetAllPoints(texture)
	texture:AddMaskTexture(mask)
end
View.AddCircleMask = addCircleMask

local function solidCircle(parent, layer, r, g, b, a)
	local t = parent:CreateTexture(nil, layer)
	t:SetColorTexture(r, g, b, a)
	t:SetPoint("CENTER")
	addCircleMask(parent, t)
	return t
end

-- Texture:SetRotation turns counter-clockwise for positive radians; slice angles are clockwise.
local function rotateClockwise(texture, degrees)
	texture:SetRotation(-math.rad(degrees))
end

local ViewMixin = {}

function View.Create(parent, opts)
	opts = opts or {}
	local v = setmetatable({
		slots = {}, wedges = {}, n = 0, hasArt = false, opts = opts,
		highlighted = nil, emphasis = nil,
		hlAngle = 0, hlTargetAngle = 0, hlAlpha = 0, hlTargetAlpha = 0,
	}, { __index = ViewMixin })

	local f = CreateFrame("Frame", opts.name, parent)
	v.frame = f

	v.backdrop = solidCircle(f, "BACKGROUND", 0, 0, 0, 0.55)
	v.deadDisc = solidCircle(f, "BORDER", 1, 1, 1, 0.07)

	v.hlGlow = f:CreateTexture(nil, "BACKGROUND", nil, 2)
	v.hlGlow:SetPoint("CENTER")
	v.hlGlow:SetBlendMode("ADD")
	v.hlGlow:SetVertexColor(GOLD[1], GOLD[2], GOLD[3], 0.9)
	v.hl = f:CreateTexture(nil, "BACKGROUND", nil, 3)
	v.hl:SetPoint("CENTER")
	v.hl:SetBlendMode("ADD")
	v.hl:SetVertexColor(GOLD[1], GOLD[2], GOLD[3], 0.38)

	v.centreIcon = f:CreateTexture(nil, "ARTWORK")
	ns.CropIcon(v.centreIcon)
	addCircleMask(f, v.centreIcon)
	v.centreLabel = f:CreateFontString(nil, "OVERLAY", opts.labelFont or "GameFontHighlightLarge")
	v.centreLabel:SetPoint("TOP", v.centreIcon, "BOTTOM", 0, -3)
	v.centreLabel:SetWordWrap(false)
	return v
end

---------------------------------------------------------------------------
-- Internals
---------------------------------------------------------------------------
function ViewMixin:SetHighlightAlpha(a)
	self.hlAlpha = a
	self.hl:SetAlpha(a)
	self.hlGlow:SetAlpha(a)
end

function ViewMixin:SetHighlightAngle(deg)
	self.hlAngle = deg % 360
	rotateClockwise(self.hl, self.hlAngle)
	rotateClockwise(self.hlGlow, self.hlAngle)
end

-- Scaling a frame also scales its anchor offsets, so re-anchor with offset / scale.
local function placeSlot(view, s)
	s:SetScale(s.scale)
	s:SetPoint("CENTER", view.frame, "CENTER", s.x / s.scale, s.y / s.scale)
end

function ViewMixin:GetSlot(i)
	local s = self.slots[i]
	if s then return s end
	s = CreateFrame("Button", nil, self.frame)
	s.index = i
	s:EnableMouse(self.opts.interactive and true or false)

	s.glow = solidCircle(s, "BACKGROUND", GOLD[1], GOLD[2], GOLD[3], 0.45)
	s.glow:SetBlendMode("ADD")
	s.glow:Hide()

	-- Thin 1px outline: the icon is cropped (ns.CropIcon) so its artwork reaches the ring.
	s.ring = solidCircle(s, "BORDER", 0, 0, 0, 0.9)

	s.icon = s:CreateTexture(nil, "ARTWORK")
	s.icon:SetAllPoints()
	ns.CropIcon(s.icon)
	addCircleMask(s, s.icon)

	if self.opts.interactive then
		local hover = solidCircle(s, "HIGHLIGHT", 1, 1, 1, 0.18)
		hover:ClearAllPoints()
		hover:SetAllPoints(s.icon)
	end

	s.key = s:CreateFontString(nil, "OVERLAY", "NumberFontNormalSmall")
	s.key:SetPoint("TOPLEFT", -3, 3)

	s.scale, s.target, s.x, s.y = 1, 1, 0, 0
	self.slots[i] = s
	if self.opts.onSlotCreated then self.opts.onSlotCreated(s, i) end
	return s
end

function ViewMixin:GetWedge(i)
	local w = self.wedges[i]
	if not w then
		w = self.frame:CreateTexture(nil, "BACKGROUND", nil, 1)
		w:SetPoint("CENTER")
		self.wedges[i] = w
	end
	return w
end

---------------------------------------------------------------------------
-- Public
---------------------------------------------------------------------------
-- Lay out `slices` (array of slice definitions). Keeps the highlight where it is when the slice
-- count is unchanged, so callers can re-layout freely without the highlight jumping.
function ViewMixin:Layout(slices, o)
	local n = #slices
	local hadArt, oldN = self.hasArt, self.n
	self.n, self.radius, self.deadZone, self.iconSize = n, o.radius, o.deadZone, o.iconSize

	local f = self.frame
	local size = 2 * (o.radius + o.iconSize)
	f:SetSize(size, size)
	local outer = o.radius + o.iconSize * 0.85 -- visual outer edge of the wheel
	self.backdrop:SetSize(2 * outer, 2 * outer)
	self.deadDisc:SetSize(2 * o.deadZone, 2 * o.deadZone)
	self.centreIcon:SetSize(o.centreIconSize, o.centreIconSize)
	self.centreIcon:SetPoint("CENTER", 0, o.centreIconSize * 0.28)

	self.hasArt = n >= WEDGE_MIN and n <= WEDGE_MAX
	self.backdrop:SetShown(not self.hasArt)
	self.hl:SetShown(self.hasArt)
	self.hlGlow:SetShown(self.hasArt)
	if self.hasArt then
		local texSize = 2 * outer / WEDGE_OUTER
		self.hl:SetTexture(MEDIA .. "wedge_" .. n)
		self.hl:SetSize(texSize, texSize)
		self.hlGlow:SetTexture(MEDIA .. "wedge_" .. n .. "_glow")
		self.hlGlow:SetSize(texSize / GLOW_SCALE, texSize / GLOW_SCALE)
		for i = 1, n do
			local w = self:GetWedge(i)
			w:SetTexture(MEDIA .. "wedge_" .. n)
			w:SetSize(texSize, texSize)
			rotateClockwise(w, ns.Geometry.SliceAngle(i, n))
			local empty = not ns.Slices.HasAction(slices[i])
			w:SetVertexColor(WEDGE_COLOR[1], WEDGE_COLOR[2], WEDGE_COLOR[3], empty and WEDGE_EMPTY_ALPHA or WEDGE_COLOR[4])
			w:Show()
		end
	end
	for i = (self.hasArt and n or 0) + 1, #self.wedges do
		self.wedges[i]:Hide()
	end

	for i, slice in ipairs(slices) do
		local s = self:GetSlot(i)
		s:SetSize(o.iconSize, o.iconSize)
		s.glow:SetSize(o.iconSize * 1.55, o.iconSize * 1.55)
		s.ring:SetSize(o.iconSize + 2, o.iconSize + 2)
		s.x, s.y = ns.Geometry.SlicePosition(i, n, o.radius)
		s.target = 1 -- current scale is kept so re-layouts don't pop
		s:ClearAllPoints()
		placeSlot(self, s)
		s.iconTexture = ns.Slices.Icon(slice)
		s.icon:SetTexture(s.iconTexture)
		s.label = ns.Slices.Label(slice)
		s.empty = not ns.Slices.HasAction(slice)
		s.chat = ns.Slices.IsChat(slice)
		s.icon:SetAlpha(s.empty and 0.35 or 1)
		s.key:SetText(ns.Slices.KeyLabel(i))
		s.glow:Hide()
		s:Show()
	end
	for i = n + 1, #self.slots do
		self.slots[i]:Hide()
	end
	self.emphasis = nil

	if n ~= oldN or self.hasArt ~= hadArt then
		self:ResetHighlight()
	end
end

-- Snap every icon back to normal size (e.g. when the wheel opens).
function ViewMixin:ResetSlots()
	for i = 1, self.n do
		local s = self.slots[i]
		s.target, s.scale = 1, 1
		placeSlot(self, s)
		s.glow:Hide()
	end
	self.emphasis = nil
end

function ViewMixin:ResetHighlight()
	self.highlighted = nil
	self.hlTargetAlpha = 0
	self:SetHighlightAlpha(0)
end

function ViewMixin:SetEmphasis(i)
	local old = self.emphasis and self.slots[self.emphasis]
	if old then
		old.target = 1
		old.glow:Hide()
	end
	self.emphasis = i
	local s = i and self.slots[i]
	if s then
		s.target = EMPHASIS_SCALE
		if not self.hasArt then s.glow:Show() end
	end
end

-- Ease the gold segment to slice i. Appearing from nothing snaps to the slice instead of sweeping
-- in from a stale angle; `snap` forces that.
function ViewMixin:SetHighlight(i, snap)
	local previous = self.highlighted
	self.highlighted = i
	if not self.hasArt then return end
	if i then
		self.hlTargetAngle = ns.Geometry.SliceAngle(i, self.n)
		if snap or not previous then self:SetHighlightAngle(self.hlTargetAngle) end
		self.hlTargetAlpha = 1
	else
		self.hlTargetAlpha = 0 -- fade out in place
	end
end

-- Lock the highlight onto slice i at full strength immediately (used when a slice fires).
function ViewMixin:Flash(i)
	self.highlighted = i
	if not self.hasArt then return end
	self.hlTargetAngle = ns.Geometry.SliceAngle(i, self.n)
	self:SetHighlightAngle(self.hlTargetAngle)
	self.hlTargetAlpha = 1
	self:SetHighlightAlpha(1)
end

function ViewMixin:SetCentre(texture, text, dim)
	if texture then
		self.centreIcon:SetTexture(texture)
		self.centreIcon:Show()
	else
		self.centreIcon:Hide()
	end
	self.centreLabel:SetText(text or "")
	if dim then
		self.centreLabel:SetTextColor(0.6, 0.6, 0.6)
	else
		self.centreLabel:SetTextColor(1, 1, 1)
	end
end

function ViewMixin:Update(elapsed)
	local k = math.min(1, elapsed * SCALE_SPEED)
	for i = 1, self.n do
		local s = self.slots[i]
		if math.abs(s.target - s.scale) > 0.002 then
			s.scale = s.scale + (s.target - s.scale) * k
			placeSlot(self, s)
		end
	end

	if self.hasArt then
		local turn = ns.Geometry.AngleDelta(self.hlAngle, self.hlTargetAngle)
		if math.abs(turn) > 0.05 then
			self:SetHighlightAngle(self.hlAngle + turn * math.min(1, elapsed * HIGHLIGHT_TURN))
		end
		local fade = self.hlTargetAlpha - self.hlAlpha
		if math.abs(fade) > 0.005 then
			self:SetHighlightAlpha(self.hlAlpha + fade * math.min(1, elapsed * HIGHLIGHT_FADE))
		end
	end
end
