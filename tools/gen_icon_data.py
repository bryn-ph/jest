"""Generate Jest/Config/IconData.lua: the name of every icon, so the icon picker can search them.

The client hands addons icons as bare file IDs; their names (e.g. Spell_Holy_PrayerOfHealing)
only exist in the game's ManifestInterfaceData table, which wago.tools publishes as CSV per
product/build. Only files in Interface\\Icons\\ are kept.

The names are written as one long string ("<fileID> <name>" per line) rather than a Lua table,
so loading the addon costs a single string; the picker parses it the first time it opens.

Re-run after a patch adds icons:
    .venv\\Scripts\\python tools\\gen_icon_data.py                 # latest Forever build
    .venv\\Scripts\\python tools\\gen_icon_data.py --build 1.60.1.70938
"""
import argparse
import csv
import io
import json
import pathlib
import re
import urllib.request

UA = {"User-Agent": "jest-addon-build"}
OUT = pathlib.Path(__file__).resolve().parents[1] / "Jest" / "Config" / "IconData.lua"
ICON_DIR = "interface\\icons\\"
# Names go inside a Lua long string, one per line: no control characters, and no "]" (which
# could close the string). Some real names have spaces, apostrophes or "&".
NAME_RE = re.compile(r"^[^\x00-\x1f\]]+$")


def fetch(url: str) -> bytes:
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=120) as resp:
        return resp.read()


def latest_build(product: str) -> str:
    builds = json.loads(fetch("https://wago.tools/api/builds"))
    return builds[product][0]["version"]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--product", default="wowf", help="wago.tools product (default: wowf = WoW: Forever)")
    parser.add_argument("--build", help="exact build version (default: latest for --product)")
    args = parser.parse_args()
    build = args.build or latest_build(args.product)

    data = fetch(f"https://wago.tools/db2/ManifestInterfaceData/csv?build={build}").decode("utf-8")
    names = {}
    skipped = 0
    for row in csv.DictReader(io.StringIO(data)):
        if row["FilePath"].lower() != ICON_DIR:
            continue
        name = re.sub(r"(\.tga)?\.blp$", "", row["FileName"], flags=re.IGNORECASE).strip()
        if not NAME_RE.match(name) or not row["ID"].isdigit():
            skipped += 1
            continue
        names[int(row["ID"])] = name

    lines = [
        "-- GENERATED by tools/gen_icon_data.py from the wago.tools DB2 table ManifestInterfaceData,",
        f"-- product {args.product} build {build}. Do not edit by hand.",
        '-- One "<fileID> <icon name>" per line, for the icon picker\'s search (Config/IconPicker.lua).',
        "local _, ns = ...",
        "",
        "ns.IconDataBuild = " + json.dumps(f"{args.product} {build}"),
        "ns.IconNames = [==[",
    ]
    lines += [f"{file_id} {names[file_id]}" for file_id in sorted(names)]
    lines.append("]==]")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(names)} icon names from {args.product} {build} to {OUT} ({OUT.stat().st_size // 1024} KB)")
    if skipped:
        print(f"  skipped {skipped} files with unexpected names")


if __name__ == "__main__":
    main()
