"""Generate Jest/Core/EmoteData.lua: which emotes play an animation and/or a voice line.

The game client exposes no API for this, but its data tables do, and wago.tools publishes them
as CSV:
    EmotesText       Name (the emote token, e.g. WAVE) -> EmoteID
    Emotes           AnimID (> 0 = animation) and EmoteSpecProc (1 = state such as sit/sleep,
                     2 = looping such as dance; both visibly animate the character)
    EmotesTextSound  rows per race/sex with a voice SoundID -> the emote has a voice line

Re-run when a patch adds emotes:
    .venv\\Scripts\\python tools\\gen_emote_data.py
"""
import csv
import datetime
import io
import pathlib
import urllib.request

BASE = "https://wago.tools/db2/{}/csv"
OUT = pathlib.Path(__file__).resolve().parents[1] / "Jest" / "Core" / "EmoteData.lua"


def table(name: str) -> list[dict]:
    req = urllib.request.Request(BASE.format(name), headers={"User-Agent": "jest-addon-build"})
    with urllib.request.urlopen(req, timeout=60) as resp:
        return list(csv.DictReader(io.StringIO(resp.read().decode("utf-8"))))


def to_int(v: str) -> int:
    try:
        return int(v)
    except (TypeError, ValueError):
        return 0


def main() -> None:
    texts = table("EmotesText")
    emotes = {r["ID"]: r for r in table("Emotes")}
    voiced = {r["EmotesTextID"] for r in table("EmotesTextSound") if to_int(r.get("SoundID")) > 0}

    flags = {}
    for t in texts:
        token = t["Name"].strip().upper()
        if not token:
            continue
        e = emotes.get(t["EmoteID"])
        anim = bool(e) and (to_int(e["AnimID"]) > 0 or to_int(e["EmoteSpecProc"]) in (1, 2))
        voice = t["ID"] in voiced
        flags[token] = ("A" if anim else "") + ("V" if voice else "")

    lines = [
        "-- GENERATED by tools/gen_emote_data.py from wago.tools DB2 tables",
        f"-- (EmotesText, Emotes, EmotesTextSound) on {datetime.date.today().isoformat()}. Do not edit by hand.",
        '-- Per emote token: "A" = plays an animation, "V" = plays a voice line, "" = text only.',
        "local _, ns = ...",
        "",
        "ns.EmoteData = {",
    ]
    for token in sorted(flags):
        lines.append(f'\t{token} = "{flags[token]}",')
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")

    counts = {k: sum(1 for v in flags.values() if v == k) for k in ("AV", "A", "V", "")}
    print(f"wrote {len(flags)} emotes to {OUT}")
    print(f"  anim+voice {counts['AV']}, anim only {counts['A']}, voice only {counts['V']}, text only {counts['']}")


if __name__ == "__main__":
    main()
