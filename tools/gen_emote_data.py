"""Generate Jest/Core/EmoteData.lua: which emotes play an animation, and which races hear a voice line.

The game client exposes no API for this, but its data tables do, and wago.tools publishes them
as CSV per product/build:
    EmotesText       Name (the emote token, e.g. WAVE) -> EmoteID
    Emotes           AnimID (> 0 = animation) and EmoteSpecProc (1 = state such as sit/sleep,
                     2 = looping such as dance; both visibly animate the character)
    EmotesTextSound  one row per race/sex with a voice SoundID

Uses WoW: Forever's own build by default ("wowf"). Its emote data differs a lot from retail:
many voice lines exist only for some races, so voice is stored per race (and per sex where the
two differ) and checked against the player's character in-game.

Re-run when a patch changes emotes:
    .venv\\Scripts\\python tools\\gen_emote_data.py                 # latest Forever build
    .venv\\Scripts\\python tools\\gen_emote_data.py --build 1.60.1.70888
"""
import argparse
import collections
import csv
import io
import json
import pathlib
import re
import sys
import urllib.request

UA = {"User-Agent": "jest-addon-build"}
OUT = pathlib.Path(__file__).resolve().parents[1] / "Jest" / "Core" / "EmoteData.lua"
SEX = {0: "m", 1: "f"}  # EmotesTextSound.SexID
# Tokens are written into Lua source as table keys, so only plain identifiers are accepted.
TOKEN_RE = re.compile(r"^[A-Z][A-Z0-9_]*$")


def fetch(url: str) -> bytes:
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as resp:
        return resp.read()


def latest_build(product: str) -> str:
    builds = json.loads(fetch("https://wago.tools/api/builds"))
    return builds[product][0]["version"]


def table(name: str, build: str) -> list[dict]:
    data = fetch(f"https://wago.tools/db2/{name}/csv?build={build}").decode("utf-8")
    return list(csv.DictReader(io.StringIO(data)))


def to_int(v) -> int:
    try:
        return int(v)
    except (TypeError, ValueError):
        return 0


def lua_voice(races: dict[int, set[int]]) -> str:
    """{1: {0, 1}, 96: {1}} -> '1, "96f"' (a bare race id means both sexes)."""
    parts = []
    for race in sorted(races):
        sexes = races[race]
        if sexes >= {0, 1}:
            parts.append(str(race))
        else:
            parts.extend(f'"{race}{SEX[s]}"' for s in sorted(sexes) if s in SEX)
    return ", ".join(parts)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--product", default="wowf", help="wago.tools product (default: wowf = WoW: Forever)")
    parser.add_argument("--build", help="exact build version (default: latest for --product)")
    args = parser.parse_args()
    build = args.build or latest_build(args.product)

    texts = table("EmotesText", build)
    emotes = {r["ID"]: r for r in table("Emotes", build)}
    voice = collections.defaultdict(lambda: collections.defaultdict(set))
    for r in table("EmotesTextSound", build):
        if to_int(r.get("SoundID")) > 0:
            voice[r["EmotesTextID"]][to_int(r["RaceID"])].add(to_int(r["SexID"]))

    entries = {}
    for t in texts:
        token = t["Name"].strip().upper()
        if not TOKEN_RE.match(token):
            if token:
                print(f"skipping unexpected emote name {token!r}", file=sys.stderr)
            continue
        e = emotes.get(t["EmoteID"])
        anim = bool(e) and (to_int(e["AnimID"]) > 0 or to_int(e["EmoteSpecProc"]) in (1, 2))
        entries[token] = (anim, voice.get(t["ID"], {}))

    lines = [
        f"-- GENERATED by tools/gen_emote_data.py from wago.tools DB2 tables (EmotesText, Emotes,",
        f"-- EmotesTextSound), product {args.product} build {build}. Do not edit by hand.",
        "-- anim  = the emote plays an animation",
        '-- voice = race IDs whose characters speak a voice line; "96f" / "96m" = that race, one sex only',
        "local _, ns = ...",
        "",
        "ns.EmoteDataBuild = " + json.dumps(f"{args.product} {build}"),
        "ns.EmoteData = {",
    ]
    for token in sorted(entries):
        anim, races = entries[token]
        fields = []
        if anim:
            fields.append("anim = true")
        if races:
            fields.append("voice = { " + lua_voice(races) + " }")
        lines.append(f"\t{token} = {{ {', '.join(fields)} }}," if fields else f"\t{token} = {{}},")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    counts = collections.Counter((anim, bool(races)) for anim, races in entries.values())
    print(f"wrote {len(entries)} emotes from {args.product} {build} to {OUT}")
    print(f"  anim+voice {counts[(True, True)]}, anim only {counts[(True, False)]}, "
          f"voice only {counts[(False, True)]}, text only {counts[(False, False)]}")


if __name__ == "__main__":
    main()
